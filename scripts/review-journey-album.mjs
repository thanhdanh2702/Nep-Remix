import { chromium } from 'playwright';
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://localhost:3000');
await page.getByRole('button', { name: /^(Vào game|Tiếp tục chơi)$/ }).click();
await page.getByRole('button', { name: 'Cốt truyện', exact: true }).first().click();
await page.locator('[data-chapter="c3"]').click();
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/journey-album-refined-desktop.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('[data-chapter="c2"]').click();
await page.locator('[data-chapter="c3"]').click();
await page.waitForTimeout(200);
await page.screenshot({ path: 'artifacts/journey-album-refined-mobile.png' });
console.log(JSON.stringify({ errors, pageWidth: await page.evaluate(() => document.documentElement.scrollWidth), enterEnabled: await page.locator('.journey-enter-chapter').isEnabled() }));
await browser.close();
